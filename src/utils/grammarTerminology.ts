export function localizeGrammarLabel(text: string, mode: GrammarTerminologyMode): string {
  if (!text || mode === 'bengali') return text;
  let result = text;
  for (const [pattern, arTerm] of BN_TO_AR_REPLACEMENTS) {
    result = result.replace(pattern, arTerm);
  }
  return result;
}
