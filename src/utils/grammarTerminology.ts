export function formatGrammarTerm(
  key: string,
  mode: GrammarTerminologyMode
): { primary: string; secondary: string; tooltipBn: string; ar: string; bn: string } {
  const entry = GRAMMAR_TERMS[key] || {
    key,
    ar: key,
    bn: key,
    tooltipBn: '',
  };
  return {
    primary: mode === 'arabic' ? entry.ar : entry.bn,
    secondary: mode === 'arabic' ? entry.bn : entry.ar,
    tooltipBn: entry.tooltipBn ? `${entry.bn}: ${entry.tooltipBn}` : entry.bn,
    ar: entry.ar,
    bn: entry.bn,
  };
}

